import { afterEach, expect, it, vi } from "vitest";
import { cleanup, fireEvent, render, screen, act } from "@testing-library/react";
import { ResourceInspection } from "./ResourceInspection";
import { api, type ResourceInspection as Inspection } from "./api";
vi.mock("./api", () => ({ api: { inspectResource: vi.fn() } }));
afterEach(() => { cleanup(); vi.clearAllMocks(); });
const data: Inspection = { id: 8, resource_type_id: 2, external_id: "book-B2", owner_identity_id: 5, path_parameter: "book_id", request_previews: [{operation_id: 3, method: "GET", path: "/books/book-B2"}] };
it("reveals only on demand, hides and reads again after remount", async () => {
  vi.mocked(api.inspectResource).mockResolvedValue(data);
  const view = render(<ResourceInspection projectId={4} resourceId={8} />);
  expect(api.inspectResource).not.toHaveBeenCalled();
  fireEvent.click(screen.getByRole("button", { name: "Xem ID đã lưu" }));
  expect(await screen.findByText("book-B2")).toBeInTheDocument();
  expect(screen.getByText("GET /books/book-B2")).toBeInTheDocument();
  expect(api.inspectResource).toHaveBeenCalledWith(4, 8);
  fireEvent.click(screen.getByRole("button", {name: "Ẩn ID"}));
  expect(screen.queryByText("book-B2")).not.toBeInTheDocument();
  view.unmount();
  render(<ResourceInspection projectId={4} resourceId={8} />);
  expect(screen.queryByText("book-B2")).not.toBeInTheDocument();
  fireEvent.click(screen.getByRole("button", {name: "Xem ID đã lưu"}));
  expect(await screen.findByText("book-B2")).toBeInTheDocument();
  expect(api.inspectResource).toHaveBeenCalledTimes(2);
});
it("ignores pending response when hidden and allows a retry after failure", async () => {
  let resolve!: (value: Inspection) => void;
  vi.mocked(api.inspectResource).mockReturnValueOnce(new Promise(r => {resolve = r;}));
  render(<ResourceInspection projectId={4} resourceId={8} />);
  fireEvent.click(screen.getByRole("button", {name: "Xem ID đã lưu"}));
  Object.defineProperty(document, "hidden", {configurable: true, value: true});
  fireEvent(document, new Event("visibilitychange"));
  await act(async () => { resolve(data); });
  expect(screen.queryByText("book-B2")).not.toBeInTheDocument();
  Object.defineProperty(document, "hidden", {configurable: true, value: false});
  vi.mocked(api.inspectResource).mockRejectedValueOnce(new Error("private response"));
  fireEvent.click(screen.getByRole("button", {name: "Xem ID đã lưu"}));
  expect(await screen.findByRole("alert")).toHaveTextContent("Không xem được ID");
  expect(screen.queryByText("private response")).not.toBeInTheDocument();
  vi.mocked(api.inspectResource).mockResolvedValueOnce(data);
  fireEvent.click(screen.getByRole("button", {name: "Xem ID đã lưu"}));
  expect(await screen.findByText("book-B2")).toBeInTheDocument();
});
