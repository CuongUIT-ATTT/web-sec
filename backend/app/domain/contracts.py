"""Explicit execution, authorization and reason-code contracts."""

from __future__ import annotations

from enum import StrEnum


class ExecutionStatus(StrEnum):
    COMPLETED_RESPONSE = "COMPLETED_RESPONSE"
    NETWORK_ERROR = "NETWORK_ERROR"
    TIMEOUT = "TIMEOUT"
    SCOPE_BLOCKED = "SCOPE_BLOCKED"
    REQUEST_LIMIT_REACHED = "REQUEST_LIMIT_REACHED"
    BODY_TRUNCATED = "BODY_TRUNCATED"
    JSON_PARSE_ERROR = "JSON_PARSE_ERROR"
    CANCELLED = "CANCELLED"
    INTERNAL_ERROR = "INTERNAL_ERROR"


class AuthorizationConclusion(StrEnum):
    CONFIRMED_VIOLATION = "CONFIRMED_VIOLATION"
    POLICY_CONSISTENT_CASE = "POLICY_CONSISTENT_CASE"
    INSUFFICIENT_EVIDENCE = "INSUFFICIENT_EVIDENCE"
    INVALID_TEST = "INVALID_TEST"
    BLOCKED_POLICY_CONFLICT = "BLOCKED_POLICY_CONFLICT"
    NOT_EVALUATED = "NOT_EVALUATED"


class PolicyDecision(StrEnum):
    ALLOW = "ALLOW"
    DENY = "DENY"
    UNKNOWN = "UNKNOWN"


class PolicyResolutionStatus(StrEnum):
    RESOLVED = "RESOLVED"
    UNRESOLVED_CONFLICT = "UNRESOLVED_CONFLICT"
    NO_MATCH = "NO_MATCH"


class RunStatus(StrEnum):
    QUEUED = "QUEUED"
    RUNNING = "RUNNING"
    CANCEL_REQUESTED = "CANCEL_REQUESTED"
    CANCELLED = "CANCELLED"
    COMPLETED = "COMPLETED"
    FAILED = "FAILED"
    INTERRUPTED = "INTERRUPTED"
